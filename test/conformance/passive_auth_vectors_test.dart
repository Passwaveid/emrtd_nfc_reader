String _hex(List<int> bytes) =>
    bytes.map((b) => b.toRadixString(16).padLeft(2, '0')).join();

final String _time = pkiVerificationTime.toIso8601String();

List<String> get _defaultTrust => [_hex(cscaRsaCert), _hex(cscaEcCert)];
List<String> get _linkTrust => [_hex(cscaOldCert), _hex(cscaLinkCert)];
List<String> get _anchorTrust => [_hex(dscSelfSignedCert)];

Map<String, Object?> get _dataGroups => {
  'DG1': _hex(hx(dg1GoodHex)),
  'DG2': _hex(hx(dg2Hex)),
};

Map<String, Object?> get _tamperedDataGroups => {
  'DG1': _hex(hx(dg1TamperedHex)),
  'DG2': _hex(hx(dg2Hex)),
};

Map<String, Object?> _case(
  String name,
  String op,
  Map<String, Object?> input,
  Map<String, Object?> expect, {
  List<String>? runners,
  String? description,
}) => {
  'name': name,
  'op': op,
  if (runners != null) 'runners': runners,
  if (description != null) 'description': description,
  'input': input,
  'expect': expect,
};

/// Signature-only input.
Map<String, Object?> _sig(List<int> sod) => {'sod': _hex(sod)};

/// Trust/verdict input.
Map<String, Object?> _full(
  List<int> sod, {
  List<String>? trust,
  Map<String, Object?>? dataGroups,
}) => {
  'sod': _hex(sod),
  'trust': trust ?? _defaultTrust,
  if (dataGroups != null) 'dataGroups': dataGroups,
  'verificationTime': _time,
};

