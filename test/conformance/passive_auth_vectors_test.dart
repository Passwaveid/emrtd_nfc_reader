/// The `passive_auth.json` generator, and its drift guard.
///
/// The fixture bytes in the committed suite are produced by the deterministic
/// test PKI (`test/support/emrtd_test_pki.dart` +
/// `test/support/pki_fixtures.dart`), and the expectations are authored
/// by hand from the spec; nothing here reads the implementation, so the
/// vectors stay an independent oracle.
///
/// Normal runs **compare**: if the generator and the committed file disagree,
/// something drifted and this test fails. To regenerate after a deliberate
/// fixture change:
///
/// ```sh
/// REGENERATE_PASSIVE_AUTH_VECTORS=1 flutter test \
///     test/conformance/passive_auth_vectors_test.dart
/// ```
///
/// The generated bytes were cross-checked against OpenSSL 3.0.13 at authoring
/// time: commands and results in `test/pki/README-fixtures.md`.
