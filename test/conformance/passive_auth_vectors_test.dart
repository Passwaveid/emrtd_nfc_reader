              'CN=${spec.issuerCn},'
              'O=${spec.lowercaseIssuer ? _orgLower : _org},C=UT',
          'serialNumber': spec.serial.toRadixString(16).toUpperCase(),
          'notBefore': spec.notBefore,
          'notAfter': spec.notAfter,
          'ski': _hex(keyIdentifierFor(spec.subjectKey)),
          'aki': spec.hasAki ? _hex(keyIdentifierFor(spec.issuerKey)) : null,
          'ca': spec.ca,
          'keyCertSign': spec.keyCertSign,
          'fingerprintSha256': _sha256Fingerprint(spec.der),
          'publicKeyBits': spec.keyBits,
          'publicKeyCurve': spec.keyCurve,
        },
      },
      runners: ['dart'],
    ),
];

